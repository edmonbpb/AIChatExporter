package com.example.data.remote.gemini

import com.example.data.model.ChatSession
import com.example.data.model.DistillationType

object DistillationPrompts {

    fun buildPrompt(session: ChatSession, type: DistillationType, customInstruction: String? = null): String {
        val transcript = session.messages.joinToString("\n\n") { msg ->
            "--- ${msg.role.name} ---\n${msg.content}"
        }

        return when (type) {
            DistillationType.REPAIR_DEFECTS_ONLY -> """
شما یک دستیار تخصصی پالایش و تصحیح فنی و کاراکتری متن هستید.
مأموریت بسیار حیاتی و دقیق شما:
تنها و تنها رفع ایرادات فنی، کاراکترهای خراب و به‌هم‌ریختگی‌های چیدمانی بدون هیچ‌گونه دستکاری در کلمات، معانی یا لحن متن!

قوانین قطعی و الزامی:
۱. اصل متن و تک‌تک جملات، کلمات و نوبت‌های مکالمه را عینا حفظ کن.
۲. اگر لحن محاوره‌ای، خودمانی، شکسته، عامیانه یا عامه‌پسند است، به هیچ‌وجه آن را کتابی یا رسمی نکن! لحن اصلی باید ۱۰۰٪ حفظ شود.
۳. هرگز متن را خلاصه نکن، حذف نکن و از خودت توضیحات اضافی اضافه نکن.
۴. مواردی که باید دقیقاً برطرف شوند فقط و فقط این موارد هستند:
   - حذف یا اصلاح کاراکترهای نامفهوم و خراب انکودینگ (مثل علامت سوال‌های داخل کادر  یا کاراکترهای نامفهوم [?] یا مربع‌های خالی ناشی از فونت).
   - اصلاح ایموجی‌های آسیب‌دیده یا تبدیل‌شده به کادرهای نامفهوم.
   - تبدیل حروف عربی به فارسی معیار (تبدیل «ي» به «ی» و «ك» به «ک» و «ۀ» به «هٔ»).
   - اصلاح چیدمان راست‌به‌چپ (BiDi) برای کلمات انگلیسی، اصطلاحات فنی و اعداد که در میان جملات فارسی باعث جابجایی پرانتز، نقطه، علامت تعجب یا سوال شده‌اند.
   - اصلاح بولت‌ها و خط‌تیره‌های به هم ریخته در شروع خطوط فارسی.
   - تنظیم نیم‌فاصله‌های استاندارد (ZWNJ) در کلمات چسبیده یا با فاصله زیاد (مانند «می‌شود»، «کتاب‌ها»، «گفته‌اند»).
۵. ساختار هر نوبت گفتگو (کاربر و دستیار) را با جداکننده مشخص نگه دار.

[متن مکالمه خام]:
$transcript
""".trimIndent()

            DistillationType.FULL_EDITED -> """
شما یک ویراستار و مهندس مستندسازی ارشد هوش مصنوعی هستید.
وظیفه شما ویراستاری کامل، تصحیح تایپوگرافی دوزبانه (BiDi)، اصلاح غلط‌های املایی، اعمال نیم‌فاصله‌های صحیح (ZWNJ) و ساختاربندی حرفه‌ای مکالمه زیر بدون حذف یا تحریف هیچ‌یک از اطلاعات فنی و کدها است.

قواعد خروجی:
۱. خروجی باید شامل عنوان سازمانی، مشخصات فنی گفتگو (مدل، تعداد پیام‌ها، تاریخ) و سپس متن ویراستاری‌شده باشد.
۲. تمام کدهای برنامه‌نویسی را در بلوک‌های کد مجزا با تعیین زبان (مانند ```kotlin یا ```python) حفظ کن.
۳. اصطلاحات انگلیسی درون متن فارسی را با دقت نگارشی بنویس تا پرانتزها و علائم به هم نریزند.
۴. زبان خروجی: فارسی روان و شیک همراه با حفظ اصطلاحات تخصصی انگلیسی.

[متن مکالمه خام]:
$transcript
""".trimIndent()

            DistillationType.EXECUTIVE_SUMMARY -> """
شما یک مدیر فنی و مشاور ارشد سیستم‌ها هستید.
لطفاً یک «خلاصه اجرایی و تصمیمات راهبردی (Executive Summary)» استاندارد و مدیریتی از مکالمه زیر استخراج کنید.

ساختار الزامی خروجی:
۱. 📌 **چکیده و هدف اصلی گفتگو** (در ۲ الی ۳ پاراگراف روشن)
۲. 🎯 **مهم‌ترین تصمیمات و رویکردهای فنی اتخاذشده** (بولت‌پوینت)
۳. 📊 **نکات کلیدی، معیارها و الگوهای معماری مطرح‌شده**
۴. ⚠️ **چالش‌ها، مخاطرات و راه‌حل‌های پیشنهادی**
۵. 🚀 **گام‌های بعدی و اقدامات اجرایی (Action Items)**

زبان خروجی: فارسی معیار، سازمانی و بسیار دقیق.

[متن مکالمه]:
$transcript
""".trimIndent()

            DistillationType.TECHNICAL_DOC -> """
شما معمار ارشد نرم‌افزار و مستندساز فنی هستید.
گفتگوی زیر را به یک «سند فنی، معماری و راهنمای پیاده‌سازی (Technical Specification & Implementation Guide)» تبدیل کنید.

ساختار الزامی:
# [عنوان مستند فنی]
## ۱. نمای کلی و معماری سیستم (System Architecture Overview)
## ۲. پیش‌نیازها و وابستگی‌ها (Prerequisites & Dependencies)
## ۳. طراحی اجزا و الگوهای مهندسی (Design Patterns & Components)
## ۴. راهنمای گام‌به‌گام پیاده‌سازی (Step-by-step Implementation) به همراه قطعات کامل کد
## ۵. نکات کلیدی عملکرد، امنیت و مدیریت خطا (Performance & Security)
## ۶. راهنمای عیب‌یابی و آزمایش (Troubleshooting & Testing)

تمام کدها باید خوانا، مرتب و دارای کامنت‌های توضیحی باشند.

[متن مکالمه]:
$transcript
""".trimIndent()

            DistillationType.QA_FLASHCARDS -> """
شما طراح آموزشی و پژوهشگر ارشد هستید.
مکالمه زیر را به یک «بانک پرسش و پاسخ تخصصی و فلش‌کارت‌های کلیدی (Q&A Flashcards)» تبدیل کنید تا خواننده بتواند در کمترین زمان مهم‌ترین مفاهیم و راه‌حل‌ها را بیاموزد.

فرمت هر فلش‌کارت:
### ❓ پرسش [شماره]: [عنوان دقیق سوال]
- **سطح:** [مقدماتی / متوسط / پیشرفته]
- **پاسخ جامع:** [توضیح کامل، روان و فنی]
- **نکته طلایی:** [نکته یا هشدار کلیدی]
- **نمونه کد یا فرمول:** (در صورت لزوم)

تعداد پرسش و پاسخ‌ها: بین ۵ الی ۱۰ مورد مهم و اساسی.

[متن مکالمه]:
$transcript
""".trimIndent()

            DistillationType.PURE_CODE -> """
شما یک مهندس ارشد نرم‌افزار هستید.
وظیفه شما استخراج خالص، تمیز و ساختاریافته تمامی «قطعات کد، اسکریپت‌ها، کانفیگ‌ها و معماری‌های نرم‌افزاری» موجود در مکالمه زیر است.

برای هر قطعه کد:
۱. نام پیشنهادی فایل (مانند `ProductRepository.kt` یا `docker-compose.yml`)
۲. زبان و تکنولوژی مربوطه
۳. بلوک کامل کد با هایلایت استاندارد Markdown
۴. توضیح مختصر عملکرد و نحوه استفاده در پروژه

[متن مکالمه]:
$transcript
""".trimIndent()

            DistillationType.CUSTOM_REWRITE -> """
شما دستیار هوشمند، جامع و متخصص سامانه AIChatExporter هستید.
دستور کاربر:
${customInstruction ?: "متن زیر را بررسی و خلاصه‌ای دقیق و خوانا ارائه کن."}

متن مکالمه جهت پردازش:
$transcript
""".trimIndent()
        }
    }
}
